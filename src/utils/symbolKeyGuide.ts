/**
 * Kiểm tra xem một ký tự có phải là ký tự đặc biệt yêu cầu giữ Shift hay không
 */
export function isShiftedSymbolChar(char?: string | null): boolean {
  if (!char || char.length !== 1) return false;
  return char in SYMBOL_KEY_GUIDE_MAP;
}

/**
 * Lấy thông tin hướng dẫn gõ ký tự đặc biệt kết hợp phím Shift
 */
export function getSymbolKeyGuideInfo(char?: string | null): SymbolKeyGuideInfo | null {
  if (!char || char.length !== 1) return null;
  return SYMBOL_KEY_GUIDE_MAP[char] || null;
}
